import asyncio
from ..agents.schemas import InvestigationOutput, TimelineOutput, RCAOutput, ReportOutput, SSEChunk
from ..reports.pdf_generator import generate_pdf


def _build_markdown(
    investigation: InvestigationOutput,
    timeline: TimelineOutput,
    rca: RCAOutput,
    incident_title: str,
    detected_at: str,
) -> str:
    tl_lines = "\n".join(
        f"- `{ev.timestamp[11:19]}` **[{ev.severity.upper()}]** `{ev.service}` — {ev.event}"
        for ev in timeline.events
    )
    evidence_lines = "\n".join(f"- `{e}`" for e in rca.evidence)
    factor_lines = "\n".join(f"- {f}" for f in rca.contributing_factors)

    return f"""# Incident Report: {incident_title}

**Severity:** {rca.severity}
**Detected At:** {detected_at}
**Services Affected:** {', '.join(investigation.services_affected)}
**Events Analyzed:** {investigation.event_count}

## Root Cause

**{rca.root_cause}**
Confidence: {rca.confidence_pct:.0f}%

## Timeline

{tl_lines}

## Evidence

{evidence_lines}

## Contributing Factors

{factor_lines}

---
*Generated by Autonomous Incident Commander*
"""


async def run_report(
    investigation: InvestigationOutput,
    timeline: TimelineOutput,
    rca: RCAOutput,
    incident_title: str,
    detected_at: str,
    queue: asyncio.Queue,
) -> ReportOutput:
    await queue.put(SSEChunk(
        agent="report",
        type="step",
        content="Synthesizing investigation findings into executive report..."
    ).model_dump())

    markdown = _build_markdown(investigation, timeline, rca, incident_title, detected_at)

    await queue.put(SSEChunk(
        agent="report",
        type="step",
        content="Generating PDF report..."
    ).model_dump())

    pdf_path = generate_pdf(investigation, timeline, rca, incident_title, detected_at)

    await queue.put(SSEChunk(
        agent="report",
        type="step",
        content=f"✓ Report complete. PDF ready for download.",
        metadata={"pdf_path": pdf_path},
    ).model_dump())

    return ReportOutput(
        incident_id=investigation.incident_id,
        summary=rca.root_cause,
        severity=rca.severity,
        pdf_path=pdf_path,
        markdown=markdown,
    )
